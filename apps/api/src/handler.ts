import { InvalidStoredOpportunity, loadOpportunityDetail } from "./opportunity.js";
import { type SqlDatabase } from "./sql.js";

/** No caching, no sniffing, no embedding: the response is data for a client (ADR 0016). */
const HEADERS: Readonly<Record<string, string>> = {
  "Content-Type": "application/json; charset=utf-8",
  "Content-Security-Policy": "default-src 'none'; frame-ancestors 'none'",
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "no-referrer",
  "Cache-Control": "no-store",
};

function json(body: unknown, status = 200, extra: Record<string, string> = {}): Response {
  return new Response(JSON.stringify(body), { status, headers: { ...HEADERS, ...extra } });
}

function error(status: number, code: string, message: string, extra = {}): Response {
  return json({ Error: { Code: code, Message: message } }, status, extra);
}

/** Opportunity IDs are generated by the pipeline: letters, digits, `_`, and `-`. */
const OPPORTUNITY_ROUTE = /^\/api\/v1\/opportunities\/([A-Za-z0-9_-]{1,100})$/u;

/**
 * The read route of the thin slice (ADR 0058, REQ-PROC-007 AC1):
 * `GET /api/v1/opportunities/:id` returns the opportunity with its publication, candidate, agent
 * outputs, evidence, and score, validated against `OpportunityDetailSchema`. Any other path is
 * 404 and any other method 405. It has no authentication, so it is deployed to local and
 * preview only; phase 4 adds authentication and the other routes and keeps this shape.
 */
export async function handleApiRequest(db: SqlDatabase, request: Request): Promise<Response> {
  const match = OPPORTUNITY_ROUTE.exec(new URL(request.url).pathname);
  if (match === null) {
    return error(404, "not-found", "no such route");
  }
  if (request.method !== "GET") {
    return error(405, "method-not-allowed", "only GET is allowed", { Allow: "GET" });
  }
  try {
    const detail = await loadOpportunityDetail(db, match[1] as string);
    return detail === null ? error(404, "not-found", "no such opportunity") : json(detail);
  } catch (caught) {
    if (caught instanceof InvalidStoredOpportunity) {
      return error(500, "invalid-stored-data", caught.message);
    }
    throw caught;
  }
}
